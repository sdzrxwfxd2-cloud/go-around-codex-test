#!/usr/bin/env node
// Compute public main-page stats from the live card list and the ATO/DFE data.
// ATO and DFE tile numbers use the same default rules as the ATO and DFE tabs
// (shared in tools/ato-dfe-counts.mjs). No hard-coded counts.
//   node tools/wm-public-stats.mjs          write site/wst/wm-public-stats.js, fold into fv3.js, patch first-paint HTML
//   node tools/wm-public-stats.mjs --check  exit 1 if those files are stale
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { atoDfeCounts } from "./ato-dfe-counts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

function parseJsonArray(text, key) {
  const i = text.indexOf('"' + key + '": [');
  if (i < 0) throw new Error("no " + key);
  const start = text.indexOf("[", i);
  let depth = 0, inStr = false, esc = false;
  for (let j = start; j < text.length; j++) {
    const ch = text[j];
    if (inStr) {
      if (esc) { esc = false; continue; }
      if (ch === "\\") { esc = true; continue; }
      if (ch === '"') inStr = false;
      continue;
    }
    if (ch === '"') { inStr = true; continue; }
    if (ch === "[") depth++;
    else if (ch === "]") {
      depth--;
      if (depth === 0) return JSON.parse(text.slice(start, j + 1));
    }
  }
  throw new Error("unterminated " + key);
}

const cardSrc = fs.readFileSync(path.join(root, "site/wst/wst-cards-data.js"), "utf8");
const ctx = { window: {} };
vm.runInContext(cardSrc, vm.createContext(ctx));
const cards = ctx.window.WM_CARD_HTML || [];
const cats = { international: 0, controlled: 0, uncontrolled: 0, other: 0 };
for (const h of cards) {
  const m = h.match(/data-cat="([^"]*)"/);
  const c = m ? m[1] : "";
  if (c in cats && c !== "other") cats[c]++; else cats.other++;
}
const app = fs.readFileSync(path.join(root, "site/c/appdata/app-data.51cdd70f78.js"), "utf8");
const counts = atoDfeCounts(parseJsonArray(app, "atos"), parseJsonArray(app, "dfes"));
const stats = {
  airports: cards.length,
  international: cats.international,
  controlled: cats.controlled,
  uncontrolled: cats.uncontrolled,
  heliport_or_other: cats.other,
  ato: counts.ato,
  dfe: counts.dfe,
  atoWithDto: counts.atoWithDto,
  atoAll: counts.atoAll,
  dfeValidRows: counts.dfeValidRows,
  dfeListed: counts.dfeListed,
  dfeAll: counts.dfeAll,
  atoSub: counts.atoSub,
  dfeSub: counts.dfeSub,
  generated: "2026-11-15",
  atoSource: counts.atoSource,
  dfeSource: counts.dfeSource,
  cardsSource: "public card list"
};
const out = "/* Computed public stats for the main-page box. Regenerated by tools/wm-public-stats.mjs. Not hand-edited. */\nwindow.WM_PUBLIC_STATS=" + JSON.stringify(stats) + ";\n";
const dest = path.join(root, "site/wst/wm-public-stats.js");

function expectedAtoBtn(s) {
  return '<button class="st tile glass" data-c="Valid ATO/DTO" style="--c:#30D5C8"><span class="n">' + s.ato + '</span><span class="k"><span class="d"></span>ATO/DTO</span></button>';
}
function expectedDfeBtn(s) {
  return '<button class="st tile glass" data-c="Valid DFE" style="--c:#FF6482"><span class="n">' + s.dfe + '</span><span class="k"><span class="d"></span>DFE</span></button>';
}
function patchHtml(html, s) {
  let next = html.replace(
    /<button class="st tile glass" data-c="Valid ATO\/DTO"[^>]*>[\s\S]*?<\/button>/,
    expectedAtoBtn(s)
  );
  next = next.replace(
    /<button class="st tile glass" data-c="Valid DFE"[^>]*>[\s\S]*?<\/button>/,
    expectedDfeBtn(s)
  );
  return next;
}

const htmlFiles = ["site/main.html", "site/c/main.html", "site/status_demo.html"];
let stale = false;

if (check) {
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, "utf8") : "";
  if (cur !== out) {
    console.error("wm-public-stats.js is stale. Run: node tools/wm-public-stats.mjs");
    stale = true;
  }
} else {
  fs.writeFileSync(dest, out);
  console.log("wrote site/wst/wm-public-stats.js", {
    airports: stats.airports,
    ato: stats.ato,
    atoWithDto: stats.atoWithDto,
    atoAll: stats.atoAll,
    dfe: stats.dfe,
    dfeValidRows: stats.dfeValidRows,
    dfeListed: stats.dfeListed
  });
}

const fv3path = path.join(root, "site/fv3.js");
if (fs.existsSync(fv3path)) {
  const begin = "/* WM_PUBLIC_STATS:begin */";
  const end = "/* WM_PUBLIC_STATS:end */";
  let fv = fs.readFileSync(fv3path, "utf8");
  const i = fv.indexOf(begin), j = fv.indexOf(end);
  if (i >= 0 && j > i) {
    const midStart = fv.indexOf("window.WM_PUBLIC_STATS=", i);
    const midEnd = fv.indexOf(";", midStart) + 1;
    if (midStart > i && midEnd > midStart && midEnd <= j) {
      const curLine = "window.WM_PUBLIC_STATS=" + JSON.stringify(stats) + ";";
      if (check) {
        if (fv.slice(midStart, midEnd) !== curLine) {
          console.error("fv3.js WM_PUBLIC_STATS is stale. Run: node tools/wm-public-stats.mjs");
          stale = true;
        }
      } else {
        fv = fv.slice(0, midStart) + curLine + fv.slice(midEnd);
        fs.writeFileSync(fv3path, fv);
      }
    }
  }
}

for (const rel of htmlFiles) {
  const p = path.join(root, rel);
  const cur = fs.readFileSync(p, "utf8");
  const next = patchHtml(cur, stats);
  if (!next.includes(expectedAtoBtn(stats)) || !next.includes(expectedDfeBtn(stats))) {
    console.error(rel + " is missing the ATO/DFE first-paint tiles. Run: node tools/wm-public-stats.mjs");
    stale = true;
    continue;
  }
  if (check) {
    if (cur !== next) {
      console.error(rel + " first-paint ATO/DFE tiles are stale. Run: node tools/wm-public-stats.mjs");
      stale = true;
    }
  } else if (cur !== next) {
    fs.writeFileSync(p, next);
    console.log("patched first-paint tiles in", rel);
  }
}

if (check) {
  if (stale) process.exit(1);
  console.log("wm-public-stats: ok", stats.airports, "airports,", stats.ato, "ATO (tab default),", stats.dfe, "DFE (tab default)");
}
