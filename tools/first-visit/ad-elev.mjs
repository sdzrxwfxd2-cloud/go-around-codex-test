// Build site/wst/ad-elev.js: field elevation (ft) per aerodrome card, read from the aerodrome pages
// (site/ad/<ident>.html, the "Elevation" row; the same values as the calculator's aerodrome list).
// Pages that show "—" (no published elevation) are left out, so the card falls back to the model ground height.
// Run: node tools/first-visit/ad-elev.mjs   (then bump ?v= with tools/first-visit/stamp.mjs)
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath } from "node:url";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../site");
// Page elevations that disagree with the ground at the card's own coordinates by more than 1 000 ft (checked 11 Nov 2026
// against the model ground height and the Open-Meteo 90 m terrain height). Left out, so the card uses the model ground height
// until the aerodrome data is corrected. MT to confirm the real values.
export const SUSPECT = {
  "ZA-0036": "page 6464 ft, terrain 1567 m = 5141 ft",
  FANG: "page 3357 ft, terrain 445 m = 1460 ft",
  FAOD: "page 1340 ft looks like metres: terrain 1331 m = 4367 ft",
  FARZ: "page 5331 ft (Reitz), but the card's coordinates (-22.78, 28.43) are in Limpopo, terrain 863 m = 2831 ft",
};
export function elevFromPage(html) {
  const m = /<span>Elevation<\/span><span>(-?[\d,]+) ft<\/span>/.exec(html);
  return m ? +m[1].replace(/,/g, "") : null;
}
export function build(root = ROOT) {
  const out = {}; let pages = 0, missing = 0, suspect = 0;
  for (const f of fs.readdirSync(path.join(root, "ad")).filter((f) => f.endsWith(".html")).sort()) {
    pages++;
    const e = elevFromPage(fs.readFileSync(path.join(root, "ad", f), "utf8"));
    if (e == null) { missing++; continue; }
    if (SUSPECT[f.slice(0, -5)]) { suspect++; continue; }
    out[f.slice(0, -5)] = e;
  }
  return { out, pages, missing, suspect };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { out, pages, missing, suspect } = build();
  const js = "/* Field elevation (ft) per aerodrome, from the aerodrome pages (site/ad/*.html \"Elevation\"). Generated by tools/first-visit/ad-elev.mjs.\n   " +
    pages + " pages, " + Object.keys(out).length + " with an elevation, " + missing + " not published and " + suspect + " left out as suspect (card uses the model ground height). */\n" +
    "window.WM_AD_ELEV=" + JSON.stringify(out) + ";\n";
  fs.writeFileSync(path.join(ROOT, "wst/ad-elev.js"), js);
  console.log("wrote site/wst/ad-elev.js:", Object.keys(out).length, "of", pages, "pages,", missing, "without elevation,", suspect, "suspect,", js.length, "bytes");
}
